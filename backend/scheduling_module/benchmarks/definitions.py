def _t(code, name, gender, degree=3, employment=1, position=1,
       max_units=12, min_units=4, unavailable=None):
    """ساخت رکورد استاد"""
    return {
        'code': code, 'full_name': name, 'gender': gender, 'degree': degree,
        'employment_type': employment, 'position': position,
        'max_units': max_units, 'min_units': min_units,
        'unavailable_times': unavailable or [],
    }


def _p(code, name, capacity, place_type=THEORY, gender=MIXED, facilities=None):
    """ساخت رکورد مکان"""
    return {
        'code': code, 'name': name, 'capacity': capacity, 'place_type': place_type,
        'gender': gender, 'facilities': facilities or [], 'available': True,
    }


def _c(code, name, units, teachers, expected_students, place_type=THEORY,
       course_type='تئوری', unit_type='تخصصی', gender=MIXED, priority=1,
       required_place=None, prerequisites=None):
    """ساخت رکورد درس"""
    return {
        'code': code, 'name': name, 'course_type': course_type, 'unit_type': unit_type,
        'units': units, 'priority': priority, 'gender': gender,
        'required_place_type': place_type, 'required_place': required_place,
        'expected_students': expected_students, 'teachers': list(teachers),
        'prerequisites': prerequisites or [], 'corequisites': [], 'fixed': False,
    }


def _g(name, size, required, optional=None, entry_year=1404,
       field='مهندسی کامپیوتر', degree_level='bachelor', gender=MIXED):
    """ساخت رکورد گروه دانشجویی"""
    return {
        'name': name, 'size': size, 'entry_year': entry_year,
        'field_of_study': field, 'degree_level': degree_level, 'gender': gender,
        'required_courses': list(required), 'optional_courses': list(optional or []),
    }


